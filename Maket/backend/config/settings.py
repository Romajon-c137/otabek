def _load_otabek_local_env():
    """Читает только Otabek-настройки из локального файла, не попадающего в Git."""
    path = BASE_DIR / ".env.otabek"
    if not path.exists():
        return
    allowed = {"OTABEK_API_URL", "OTABEK_USERNAME", "OTABEK_PASSWORD", "OTABEK_TIMEOUT_SECONDS"}
    for raw_line in path.read_text(encoding="utf-8-sig").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        if key in allowed and key not in os.environ:
            os.environ[key] = value.strip().strip('"').strip("'")


_load_otabek_local_env()


